"""Generate the synthetic non-speech clips, and a manifest for them. S2.2.

**The generator is committed; the audio is not.** Same principle as
``tests/corpus/authority_vi.py`` and ``addressing_vi.py``, which are committed
``.py`` files rather than committed data: ``.gitignore`` blocks ``*.wav``
because a clip is content-shaped, so the only way the repository can reproduce
this group is to carry the code that makes it.

Everything here is deterministic. The noise uses a fixed-seed linear
congruential generator rather than :mod:`random`, so the bytes are identical on
every machine and on every regeneration - a clip whose hash moves between runs
could not be pinned in the artifact ledger.

**What this group can and cannot show.** It is the control, not the realistic
case. Whisper-family models hallucinate most on low-level *speech-shaped*
noise; digital zero and flat noise at about -60 dBFS are weak stimuli against
the -50 to -35 dBFS noise floor of a real room. So this group almost certainly
**under-reports** hallucination, and the realistic version has to be cut from
the leading and trailing silence of real licensed recordings. Measured here:
even digital zero produced 15 tokens of subtitle boilerplate, so the weak
stimulus was already enough.

Run from the repository root:

    uv run python benchmarks/make_nonspeech_clips.py
"""

from __future__ import annotations

import json
import math
import pathlib
import struct
import sys
import wave

# The repository root, because `benchmarks.artifacts` is imported by package
# path and sys.path[0] is this directory when the file is run as a script.
sys.path.insert(1, str(pathlib.Path(__file__).resolve().parent.parent))

from benchmarks.artifacts import artifact_path

RATE = 16000
"""16 kHz mono, which is what whisper.cpp wants and what every Vietnamese
read-speech corpus ships."""

# S2.1 decision #2: the artifact root is fixed. These resolve to exactly the
# same places the literals named - the helper adds validation, not a new
# location - and they match `make_noise_group.py`, the sibling generator that
# already routes its manifest this way.
CLIP_ROOT = artifact_path("asr", "clips")
MANIFEST = artifact_path("asr", "manifest-nonspeech.json")


def _write(path: pathlib.Path, samples: list[float]) -> None:
    frames = b"".join(struct.pack("<h", max(-32768, min(32767, int(s)))) for s in samples)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(RATE)
        handle.writeframes(frames)


def _lcg_noise(count: int, amplitude: float, seed: int = 12345) -> list[float]:
    """Deterministic low-level noise.

    A linear congruential generator rather than :mod:`random` so the output
    does not depend on the Python version's PRNG implementation.
    """
    state = seed
    out: list[float] = []
    for _ in range(count):
        state = (1103515245 * state + 12345) & 0x7FFFFFFF
        out.append(((state / 0x7FFFFFFF) - 0.5) * 2 * amplitude)
    return out


def generate() -> list[dict[str, object]]:
    CLIP_ROOT.mkdir(parents=True, exist_ok=True)

    specs: list[tuple[str, list[float], str]] = [
        (
            "silence_digital_5s.wav",
            [0.0] * (RATE * 5),
            "digital zero: RMS 0, peak 0. The strongest probe, because there "
            "is no signal to mishear - any output at all is an insertion.",
        ),
        (
            "silence_roomnoise_5s.wav",
            _lcg_noise(RATE * 5, amplitude=60.0),
            "synthetic noise at about -60 dBFS. A quiet line rather than a "
            "quiet room; a real room floor is -50 to -35 dBFS.",
        ),
        (
            "tone_440hz_3s.wav",
            [3000 * math.sin(2 * math.pi * 440 * t / RATE) for t in range(RATE * 3)],
            "a pure 440 Hz tone. Not speech, so any transcription is an insertion.",
        ),
    ]

    clips: list[dict[str, object]] = []
    for name, samples, note in specs:
        path = CLIP_ROOT / name
        _write(path, samples)
        clips.append(
            {
                "id": path.stem,
                "file": path.name,
                # An empty reference is what marks a clip as non-speech. The
                # runner keys the whole asymmetry on this: an empty hypothesis
                # here is the CORRECT answer, not a failure.
                "reference": "",
                "duration_s": round(len(samples) / RATE, 3),
                "synthetic": True,
                "block": "synthetic_nonspeech",
                "note": note,
            }
        )
    return clips


def main() -> int:
    clips = generate()
    manifest = {
        "group": "nonspeech_synthetic",
        "clip_root": str(CLIP_ROOT).replace("\\", "/"),
        "license": "generated by benchmarks/make_nonspeech_clips.py in this repo",
        "license_branch": "permissive",
        "synthetic": True,
        "note": (
            "Synthetic non-speech, deterministic. The generator is committed; "
            "the audio is not. This group is a CONTROL and almost certainly "
            "under-reports hallucination on a real room."
        ),
        "clips": clips,
    }
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    # ASCII only on the console, per the project's terminal rule.
    print(f"clips: {len(clips)} -> {CLIP_ROOT}")
    for clip in clips:
        print(f"  {clip['id']:28} {clip['duration_s']}s")
    print(f"manifest: {MANIFEST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
