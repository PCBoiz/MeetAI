"""Mix licensed FLEURS speech with deterministic noise at known SNRs. S2.2.

Closes the **noise** axis of spec obligation B-1 without downloading anything
new. The speech is FLEURS ``vi_vn`` (CC-BY-4.0), the noise is generated by this
file, so the result is a derivative of permissively licensed audio and stays in
the permissive branch. VIVOS could add a second corpus but it is read speech
too, so it would close no additional B-1 axis while being non-commercial.

**Why this reads the WAV by hand.** FLEURS ships mono 16 kHz **32-bit IEEE
float** WAV, and stdlib :mod:`wave` raises ``unknown format: 3`` on anything
that is not integer PCM - it cannot read these files at all. The float data
chunk is parsed directly with :mod:`array` instead, and the mixed output is
written as 16-bit PCM, which `wave` *can* write and which whisper.cpp prefers.

**SNR is defined and the definition is reported**, because "with noise" is
meaningless otherwise: SNR here is the ratio of speech RMS to noise RMS over
the whole clip, in dB, with the noise scaled to hit the target. Clip-level RMS
rather than a speech-active estimate, which is the simpler and more
conservative reading - a clip with long pauses gets relatively more noise than
a voice-activity-weighted definition would give it.

The audio is never committed; this generator is. Deterministic, so a clip's
hash is stable across regenerations.
"""

from __future__ import annotations

import argparse
import array
import json
import math
import pathlib
import struct
import sys
import wave

# The repository root, because `benchmarks.artifacts` is imported by package
# path and sys.path[0] is this directory when the file is run as a script.
sys.path.insert(1, str(pathlib.Path(__file__).resolve().parent.parent))

from benchmarks.artifacts import artifact_path

RATE = 16000


def read_wav_any(path: pathlib.Path) -> tuple[list[float], int]:
    """Return (samples in [-1, 1], sample rate) for PCM-16 or float32 WAV.

    Hand-rolled because stdlib ``wave`` cannot open the float32 files this
    corpus ships. Only the subset needed here is handled, and anything else
    raises rather than guessing.
    """
    raw = path.read_bytes()
    if raw[:4] != b"RIFF" or raw[8:12] != b"WAVE":
        raise ValueError(f"khong phai RIFF/WAVE: {path.name}")

    fmt_tag = channels = bits = 0
    rate = 0
    data: bytes | None = None
    offset = 12
    while offset + 8 <= len(raw):
        chunk_id = raw[offset : offset + 4]
        size = struct.unpack_from("<I", raw, offset + 4)[0]
        body = offset + 8
        if chunk_id == b"fmt ":
            fmt_tag, channels, rate, _, _, bits = struct.unpack_from("<HHIIHH", raw, body)
        elif chunk_id == b"data":
            data = raw[body : body + size]
        offset = body + size + (size & 1)

    if data is None:
        raise ValueError(f"khong co data chunk: {path.name}")
    if channels != 1:
        raise ValueError(f"can mono, co {channels} channel: {path.name}")

    if fmt_tag == 1 and bits == 16:
        ints = array.array("h")
        ints.frombytes(data[: len(data) - (len(data) % 2)])
        return [v / 32768.0 for v in ints], rate
    if fmt_tag == 3 and bits == 32:
        floats = array.array("f")
        floats.frombytes(data[: len(data) - (len(data) % 4)])
        return list(floats), rate
    raise ValueError(f"format chua ho tro: tag={fmt_tag} bits={bits}")


def rms(samples: list[float]) -> float:
    if not samples:
        return 0.0
    return math.sqrt(sum(s * s for s in samples) / len(samples))


def lcg_noise(count: int, seed: int) -> list[float]:
    """Deterministic white noise in [-1, 1]. Same generator as the
    non-speech clips, so the two groups share one noise definition."""
    state = seed
    out: list[float] = []
    for _ in range(count):
        state = (1103515245 * state + 12345) & 0x7FFFFFFF
        out.append((state / 0x7FFFFFFF) - 0.5)
    return out


def mix_at_snr(speech: list[float], snr_db: float, seed: int) -> list[float]:
    """Add noise scaled so speech_rms / noise_rms equals the target SNR."""
    speech_rms = rms(speech)
    noise = lcg_noise(len(speech), seed)
    noise_rms = rms(noise)
    if speech_rms == 0 or noise_rms == 0:
        return list(speech)
    target_noise_rms = speech_rms / (10 ** (snr_db / 20.0))
    gain = target_noise_rms / noise_rms
    return [s + n * gain for s, n in zip(speech, noise, strict=True)]


def write_pcm16(path: pathlib.Path, samples: list[float]) -> None:
    peak = max((abs(s) for s in samples), default=0.0)
    # Scale only if mixing pushed the signal past full scale, so an unclipped
    # clip keeps its original level and the SNR stays the one that was set.
    scale = 1.0 if peak <= 1.0 else 1.0 / peak
    frames = b"".join(
        struct.pack("<h", int(max(-32768, min(32767, s * scale * 32767))))
        for s in samples
    )
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(RATE)
        handle.writeframes(frames)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-manifest", required=True, type=pathlib.Path)
    parser.add_argument("--out-root", default="var/asr/noise", type=pathlib.Path)
    parser.add_argument(
        "--snr", default="20,10,5", help="comma-separated target SNRs in dB"
    )
    parser.add_argument(
        "--clips", type=int, default=40, help="how many source clips to use"
    )
    args = parser.parse_args()

    source = json.loads(args.source_manifest.read_text(encoding="utf-8"))
    snrs = [float(x) for x in args.snr.split(",")]
    root = pathlib.Path(args.out_root)
    root.mkdir(parents=True, exist_ok=True)

    # A fixed prefix of the manifest, not a random sample, so the group is
    # reproducible without carrying a sampling seed.
    chosen = source["clips"][: args.clips]
    clip_root = pathlib.Path(source["clip_root"])

    clips: list[dict[str, object]] = []
    skipped = 0
    for entry in chosen:
        src = clip_root / entry["file"]
        if not src.is_file():
            skipped += 1
            continue
        try:
            samples, rate = read_wav_any(src)
        except ValueError:
            skipped += 1
            continue
        if rate != RATE:
            skipped += 1
            continue
        for snr_db in snrs:
            name = f"{entry['id']}-snr{int(snr_db)}.wav"
            mixed = mix_at_snr(samples, snr_db, seed=1234567)
            write_pcm16(root / name, mixed)
            clips.append(
                {
                    "id": f"{entry['id']}-snr{int(snr_db)}",
                    "file": name,
                    "reference": entry["reference"],
                    "duration_s": round(len(samples) / RATE, 3),
                    "snr_db": snr_db,
                    "source_clip": entry["id"],
                    "block": f"fleurs_noise_snr{int(snr_db)}",
                    "derived": True,
                }
            )

    manifest = {
        "group": "fleurs_vi_dev_noise",
        "clip_root": str(root).replace("\\", "/"),
        "license": "CC-BY-4.0 (derived from google/fleurs vi_vn by adding generated noise)",
        "license_branch": "permissive",
        "dataset_revision": source.get("dataset_revision"),
        "derived_from": source.get("group"),
        "snr_definition": (
            "clip-level speech RMS over noise RMS, in dB; noise is the "
            "deterministic LCG from make_noise_group.py, seed 1234567"
        ),
        "note": (
            "Closes the noise axis of spec B-1 without a new download. Still "
            "read speech with one speaker per clip, so it does NOT close the "
            "overlapping-speech axis. Additive white noise is also not room "
            "noise: a real room is spectrally shaped and reverberant."
        ),
        "clips": clips,
    }
    target = artifact_path("asr", "manifest-fleurs-noise.json")
    target.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    print(f"source clips used: {len(chosen) - skipped} (skipped {skipped})")
    print(f"snrs: {snrs}")
    print(f"clips written: {len(clips)} -> {root}")
    print(f"manifest: {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
